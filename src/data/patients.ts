export function findPatientById(id: string): CustomerRecord | undefined {
  const patient = PATIENTS.find((entry) => entry.id === id)
  if (!patient) return undefined
  return { ...patient, ...BASE_ACCOUNT_RECORD }
}

export function findPatientByName(name: string): CustomerRecord | undefined {
  const patient = PATIENTS.find((p) => p.name === name || p.name.includes(name))
  if (!patient) return undefined
  return { ...patient, ...BASE_ACCOUNT_RECORD }
}

